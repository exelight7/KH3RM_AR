r"""translation\glossary.tsv (source of truth) -> recount kh3_count/example_ids from translation\<cat>\*.tsv EN
(whole-word, case-insensitive, rows counted) and write translation\glossary.md (tables by type, approved first).
Edit the TSV, never glossary.md."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tsvlib import *
from make_review import esc

TYPES = ['character', 'world', 'place', 'item', 'ability', 'magic', 'menu', 'term']
STATUS_ORDER = {'approved': 0, 'proposed': 1, 'pending': 2, 'kh2-only': 3}
WORD = re.compile(r'\w+')

RULES = r"""## Rule order for names
1. Correct Arabic. 2. English pronunciation for names. 3. Most common usage. 4. Shortest.
Same English term = same Arabic everywhere. A term marked `pending` or `proposed` is not used in bulk until the user approves it.

## KH2 rules that do NOT apply to KH3
KH2 used a fixed-cell bitmap atlas; KH3 uses a rebuilt TresFont (Segoe UI) with real Arabic glyphs and full Latin. These KH2 rules are **not** carried over:
- **Latin-letter bans and the safe-letter list** (only `M P W H A T S I`, `D`/`C` banned, no lowercase). KH3 (TRANS-2 policy, final): the game font renders every Latin letter, digit, Roman numeral and Greek letter of the EN text, so **any Latin/Roman/Greek token in AR must also appear verbatim in the EN of the same row** (validator ERR LATIN); `translation\allowed_latin.txt` is kept only as history. Keep as in EN: acronyms (HDR, LOD, DOF, FXAA, AP, HP, MP, UFO, AR, CDA, MVP, PC…), brand/product names (PlayStation, Epic Games, Re Mind…), rank letters (S A B C), single-letter suffixes, sector codes (SLW-01), game-title numerals (KINGDOM HEARTS Ⅲ, II.9; the words stay `كينغدوم هارتس`), Greek letters (α β γ χ), URLs, Latin units such as `p`. Exception: keep Arabic where the Arabic word is clearly more natural and short and the EN is a plain word (not an acronym), and where a glossary term is approved in Arabic (EXP = خبرة, LV = مستوى, EZ/PRO Codes).
- **Arabic comma `،` is allowed and proven in-game** (TEST50 subtitle screenshot, 2026-10-09; supervisor decision TRANS-3, final): no space before it, one space after; ASCII `,` stays only inside numbers (5,000), Latin runs, tags/args/plural syntax. **Arabic question mark `؟` is still ASCII `?` until a screenshot proves it.**
- **ya / alef-maqsura rule** (`ى` written as `ي`): not used; write `ى` correctly.
- **`<X 5E>`** (KH2 atlas cell for "XIII"): does not exist in KH3. User decision GLOSS-2: Organization XIII = `منظمة XIII` (Latin XIII as in EN); "the Organization" = `المنظمة`; Real Organization XIII = `منظمة XIII الحقيقية`.
- **LV shortened to `مس`**: KH2 save-slot width only. User decision GLOSS-2: LV / Lv. = `مستوى`, Next LV = `المستوى التالي` (no `مس`).
- **Munny**: user decision GLOSS-2: `موني` in all forms (Munny Pouch = `كيس موني`); `مال`, `الموني`, `مميونة` retired.
- **Shortenings made only for KH2 cell width**: decided in TRANS-1 (Journal = `اليوميات`, Hollow Bastion = `حصن هولو`, Full Bloom = `الإزهار`, Limit = `ليميت`, Lucky Lucky = `لكي لاكي` approved). Musical = `موسيقي` and Grind = `طحن` (TRANS-2).
- **Transliterations forced only by banned Latin letters** (e.g. MCP `إم سي بي`, DTD `دي تي دي`, FPS Mode `منظور 1`, Final Fantasy `فاينل فانتسي 3..10-2`, LT `الزر الأيسر`, `دوران 360`): status `kh2-only` when KH3 has no row with the term (TRANS-1), otherwise `pending`.
- KH2 tool specifics (`<C …>` state commands, FixState, atlas cells, 150 % width WARN): KH2 only.

## KH2 rules that DO carry over
- No harakat, no tatweel.
- Tags, `{n}` args and icons kept exactly, same order.
- Same line count as EN (`<br>` count; validator rule BR).
- Names as approved in this glossary (validator WARN GLOSS when an approved name's Arabic is missing).
"""


def en_rows():
    """-> [(id, normalized EN)] of all translation rows"""
    return [(r['id'], norm_en(r['EN'])) for r in load_translation()]


def count_terms(terms, rows=None):
    """-> {term: (rows containing it, [first 3 ids])}; whole-word, case-insensitive"""
    rows = rows if rows is not None else en_rows()
    index = {}
    for i, (rid, en) in enumerate(rows):
        for w in set(WORD.findall(en.lower())):
            index.setdefault(w, set()).add(i)
    out = {}
    for t in terms:
        words = WORD.findall(norm_en(t).lower())
        if not words:
            out[t] = (0, [])
            continue
        cand = set.intersection(*(index.get(w, set()) for w in words))
        rx = term_re(t)
        hits = sorted(i for i in cand if rx.search(rows[i][1]))
        out[t] = (len(hits), [rows[i][0] for i in hits[:3]])
    return out


def write_md(g, path):
    n = {s: sum(1 for d in g if d['status'] == s) for s in STATUS_ORDER}
    L = ['# Glossary — KH3 Arabic', '',
         'Generated by `tools\\make_glossary.py` from `translation\\glossary.tsv` (the source of truth — edit the TSV, not this file).',
         f'Entries: {len(g)} — approved {n["approved"]}, proposed {n["proposed"]}, pending {n["pending"]}, kh2-only {n["kh2-only"]} (KH2 constraint rows with 0 KH3 rows; not used, excluded from GLOSS checks). '
         '`kh3_count` = KH3 rows whose EN contains the term (whole word, any case; for common English words such as Will, Even, ON it includes ordinary uses). '
         'Conflicts: `translation\\GLOSSARY_CONFLICTS.md`; KH3-new proposals: `translation\\GLOSSARY_PROPOSALS.md`; '
         'full KH2 glossary (reference only): `translation\\kh2_glossary.md`.', '', RULES]
    for t in TYPES:
        part = sorted((d for d in g if d['type'] == t),
                      key=lambda d: (STATUS_ORDER.get(d['status'], 9), -int(d['kh3_count'] or 0), d['en'].lower()))
        if not part:
            continue
        L += [f'## {t} ({len(part)})', '', '| EN | AR | status | source | KH3 rows | examples | note |', '|---|---|---|---|---|---|---|']
        L += [f'| {esc(d["en"])} | {esc(d["ar"])} | {d["status"]} | {d["source"]} | {d["kh3_count"]} | {d["example_ids"]} | {esc(d["note"])} |'
              for d in part]
        L.append('')
    open(path, 'w', encoding='utf-8', newline='\n').write('\n'.join(L))


def write_proposals(g, path):
    L = ['# Glossary proposals — KH3-new and Re Mind terms', '',
         'Generated by `tools\\make_glossary.py` from `translation\\glossary.tsv` (rows with status `proposed`). '
         'For the user\'s review: to approve, set status to `approved` in the TSV (or change the Arabic first). '
         'Sorted by KH3 rows (whole word, any case).', '']
    for src, title in (('KH3-new', 'KH3 base game'), ('ReMind', 'Re Mind')):
        part = sorted((d for d in g if d['status'] == 'proposed' and d['source'] == src),
                      key=lambda d: (-int(d['kh3_count']), d['en'].lower()))
        L += [f'## {title} ({len(part)})', '', '| EN | proposed AR | type | KH3 rows | examples | reason |', '|---|---|---|---|---|---|']
        L += [f'| {esc(d["en"])} | {esc(d["ar"])} | {d["type"]} | {d["kh3_count"]} | {d["example_ids"]} | {esc(d["note"])} |' for d in part]
        L.append('')
    open(path, 'w', encoding='utf-8', newline='\n').write('\n'.join(L))


def main():
    g = load_glossary()
    counts = count_terms({d['en'] for d in g})
    for d in g:
        c, ids = counts[d['en']]
        d['kh3_count'], d['example_ids'] = str(c), ','.join(ids)
    write_tsv(GLOSSARY, [GCOLS] + [[d[c] for c in GCOLS] for d in g])
    write_md(g, os.path.join(ROOT, 'translation', 'glossary.md'))
    write_proposals(g, os.path.join(ROOT, 'translation', 'GLOSSARY_PROPOSALS.md'))
    print(f'make_glossary: {len(g)} entries, {sum(1 for d in g if d["kh3_count"] != "0")} found in KH3 EN')


if __name__ == '__main__':
    main()
