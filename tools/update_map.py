r"""Regenerate the "(auto)" sections of PROJECT_MAP.md: numbers (from state\STATS.md, so run stats.py first),
folder map (folders + key files, one line each, from docstrings / first headings) and round history (from
state\PROGRESS.md). Manual sections are never touched: a section is auto only if its "## " heading ends in "(auto)".
Usage: python -I tools\update_map.py   (called by tools\refresh.bat)"""
import ast, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tsvlib import ROOT

MAP = os.path.join(ROOT, 'PROJECT_MAP.md')
FOLDERS = {  # top-level folder -> one line; anything not listed here shows up as "(no description)"
    'docs': 'project docs: INDEX (doc list), SUPERVISOR (full supervisor instructions)',
    'extracted': 'read-only decrypted copies of game files + pak index (gitignored, never deleted)',
    'font': 'reserved for font files (empty; Segoe UI is read from C:\\Windows\\Fonts)',
    'out': 'build outputs: out\\builds\\<round>\\ paks, pakroots, verify tables (gitignored, never deleted)',
    'review': 'review pages (Markdown), corrections, validation report; **`review\\script\\` = the reference script for '
              'translation and review** (story order by the Theater table + TIPS pages, `tools\\make_script.py`)',
    'screenshots': 'optional, gitignored; screenshots are sent in the supervisor chat (log file = chat)',
    'state': 'round log, last report, stats, screenshot log',
    'technical': 'recon, tag inventory, shaper spec, text counts, field widths, text coverage (TEXT_COVERAGE.md)',
    'tools': 'all scripts (Python 3.12, run from the project root) + repak',
    'translation': 'translation TSVs per category/file (EN + AR + status), glossary',
}
FILES = {  # key files whose first line is not a description
    'allowed_latin.txt': 'history only (TRANS-1 whitelist); the LATIN rule now compares each row with its own EN',
    'PROGRESS.md': 'round log, 3 lines per task (source of the round history below)',
    'LAST_REPORT.md': 'latest round report (overwritten each round)',
    'refresh.bat': 'end-of-round pipeline: merge check, tests, corrections, validate, review pages, script, stats, map, secret check',
    'test_corrections.py': 'unit tests for apply_corrections.py',
    'test_validate.py': 'unit tests for validate.py',
}
SKIP = {'.git', '.claude', '__pycache__'}


def first_line(path):
    """one-line description: module docstring (py), first heading/line (md), header (tsv/txt), comment (bat)."""
    try:
        text = open(path, encoding='utf-8').read()
    except (UnicodeDecodeError, OSError):
        return ''
    if os.path.basename(path) in FILES:
        return FILES[os.path.basename(path)]
    if path.endswith('.tsv'):
        return 'TSV, columns: ' + ', '.join(text.split('\n', 1)[0].split('\t'))
    if path.endswith('.py'):
        try:
            doc = ast.get_docstring(ast.parse(text)) or ''
        except SyntaxError:
            doc = ''
        return doc.strip().split('\n')[0]
    for line in text.splitlines():
        line = line.strip().lstrip('#').strip()
        if line.lower().startswith('rem '):
            line = line[4:]
        if line and not line.startswith('@echo'):
            return line[:140]
    return ''


def folder_map():
    L = ['| path | what |', '|---|---|']
    for f in sorted(os.listdir(ROOT)):
        p = os.path.join(ROOT, f)
        if f in SKIP or f.startswith('.'):
            continue
        if os.path.isdir(p):
            L.append(f'| `{f}\\` | {FOLDERS.get(f, "(no description)")} |')
            if f in ('docs', 'state', 'technical', 'tools', 'review', 'translation'):
                for g in sorted(os.listdir(p)):
                    q = os.path.join(p, g)
                    if os.path.isfile(q) and g.endswith(('.md', '.py', '.bat', '.tsv', '.txt')) and g != 'KEY_SOURCE.txt':
                        d = first_line(q).replace('|', '\\|')
                        L.append(f'| `{f}\\{g}` | {d} |')
        else:
            L.append(f'| `{f}` | {first_line(p).replace("|", chr(92) + "|")} |')
    return L


def numbers():
    rows = [l for l in open(os.path.join(ROOT, 'state', 'STATS.md'), encoding='utf-8').read().splitlines() if l.startswith('|')]
    return ['From `state\\STATS.md` (regenerated by `tools\\stats.py`).', ''] + rows


def history():
    rounds = {}
    for line in open(os.path.join(ROOT, 'state', 'PROGRESS.md'), encoding='utf-8').read().splitlines():
        m = re.match(r'(\d{4}-\d\d-\d\d) (\S+) (.*)', line)
        if m:
            d, r, text = m.groups()
            rounds.setdefault(r, [d, 0, ''])
            rounds[r][1] += 1
            rounds[r][2] = text
    return [f'- {d} **{r}** ({n} entries) — last: {t}' for r, (d, n, t) in rounds.items()]


AUTO = {'Folders and key files': folder_map, 'Numbers': numbers, 'Round history': history}


def update(text):
    parts = re.split(r'(?m)^(## .*)$', text)
    out = [parts[0]]
    for head, body in zip(parts[1::2], parts[2::2]):
        name = next((k for k in AUTO if k in head and head.rstrip().endswith('(auto)')), None)
        out += [head, '\n\n' + '\n'.join(AUTO[name]()) + '\n\n' if name else body]
    return ''.join(out).rstrip('\n') + '\n'


if __name__ == '__main__':
    assert update('# T\n\n## 1. A\nkeep\n## 7. Numbers (auto)\nold\n').startswith('# T\n\n## 1. A\nkeep\n## 7. Numbers (auto)\n\nFrom')
    old = open(MAP, encoding='utf-8').read()
    heads = re.findall(r'(?m)^## .*\(auto\)[ \t]*$', old)
    missing = [k for k in AUTO if not any(k in h for h in heads)]
    if missing:  # e.g. every line prefixed with a backtick: the sections would silently stop updating
        sys.exit(f'update_map: FAIL, no "## ... (auto)" heading for {missing} in PROJECT_MAP.md (file damaged?)')
    new = update(old)
    open(MAP, 'w', encoding='utf-8', newline='\n').write(new)
    print('update_map: PROJECT_MAP.md auto sections refreshed')
