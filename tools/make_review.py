r"""Generate review\md\<category>_NN.md (300 rows/page, game order), review\INDEX.md, review\FLAGS.md
and review\review_<category>.tsv from translation\*.tsv. Plain Markdown only, no HTML."""
import os, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tsvlib import *
from validate import validate_all, ERR

PAGE = 300
NAMES = {'remind': 'Re Mind'}


def esc(t):
    if not t:
        return '—'
    t = t.replace('\r', '').replace('\\n', '\n').replace('\n', ' ⏎ ')
    for ch in '\\`*_|<':  # backslash first; game text must never render as Markdown formatting
        t = t.replace(ch, '\\' + ch)
    return t


def write(path, lines):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


def counts(rs):
    return tuple(sum(r['status'] == s for r in rs) for s in STATUSES)


def pct(a, b):
    return f'{100 * a / b:.1f}%' if b else '-'


if __name__ == '__main__':
    assert esc(r'a*b_c`d|e<f\g') == r'a\*b\_c\`d\|e\<f\\g' and esc('') == '—', esc(r'a*b_c`d|e<f\g')
    rows = load_translation()
    flags = validate_all(rows)
    md = os.path.join(ROOT, 'review', 'md')
    shutil.rmtree(md, ignore_errors=True)
    os.makedirs(md)
    where, idx_rows, links = {}, [], []
    for cat in CATEGORIES:
        rs = [r for r in rows if r['category'] == cat]
        name = NAMES.get(cat, cat)
        write_tsv(os.path.join(ROOT, 'review', f'review_{cat}.tsv'),
                  [['id', 'EN', 'AR', 'status', 'flags', 'note']] + [[r['id'], r['EN'], r['AR'], r['status'], ' '.join(flags.get(r['id'], [])), r['note']] for r in rs])
        n = (len(rs) + PAGE - 1) // PAGE
        links.append(f'### {name}')
        for p in range(n):
            chunk = rs[p * PAGE:(p + 1) * PAGE]
            fn = f'{cat}_{p + 1:02d}.md'
            td, tr, rv, vf = counts(chunk)
            L = [f'# {name} — page {p + 1}/{n}', '', f'Category: {cat} · ids {chunk[0]["id"]}–{chunk[-1]["id"]} · rows {len(chunk)}', '',
                 f'Counts: todo {td} · translated {tr} · reviewed {rv} · verified {vf}', '',
                 '| id | EN | AR | status | flags |', '|---|---|---|---|---|']
            for r in chunk:
                where[r['id']] = fn
                L.append(f'| {r["id"]} | {esc(r["EN"])} | {esc(r["AR"])} | {r["status"]} | {" ".join(flags.get(r["id"], []))} |')
            write(os.path.join(md, fn), L)
            nf = sum(r['id'] in flags for r in chunk)
            links.append(f'- [{fn[:-3]}](md/{fn}) — ids {chunk[0]["id"]}–{chunk[-1]["id"]}, flagged {nf}')
        td, tr, rv, vf = counts(rs)
        idx_rows.append((name, len(rs), len(rs) - td, rv + vf, vf))
    tot = [sum(x[i] for x in idx_rows) for i in range(1, 5)]
    im = load_images_strings()   # category "images": listed after TOTAL, not counted in it
    imc = counts(im)
    L = ['# Review index', '', 'No HTML in this project; open the pages under `md\\`. Regenerated by `tools\\make_review.py`.', '',
         '| category | rows | translated % | reviewed % | verified % |', '|---|---|---|---|---|']
    for name, n, t, rv, vf in idx_rows + [('TOTAL', *tot), ('images', len(im), len(im) - imc[0], imc[2] + imc[3], imc[3])]:
        L.append(f'| {name} | {n} | {pct(t, n)} | {pct(rv, n)} | {pct(vf, n)} |')
    cnt = {}
    for fl in flags.values():
        for c in fl:
            cnt[c] = cnt.get(c, 0) + 1
    L += ['', f'## Flags ({len(flags)} rows flagged; list: [FLAGS.md](FLAGS.md))', '', '| code | level | rows |', '|---|---|---|']
    L += [f'| {c} | {"ERR" if c in ERR else "WARN"} | {k} |' for c, k in sorted(cnt.items())] or ['| (none) | | 0 |']
    L += ['', '## Pages', ''] + links
    write(os.path.join(ROOT, 'review', 'INDEX.md'), L)
    by = {r['id']: r for r in rows}
    F = ['# Flagged rows', '', f'{len(flags)} rows with validator flags. ERR codes (must fix): {", ".join(sorted(ERR))}; the rest are WARN.', '',
         '| id | page | flag | EN | AR |', '|---|---|---|---|---|']
    for i in sorted(flags):
        r = by[i]
        F.append(f'| {i} | [{where[i][:-3]}](md/{where[i]}) | {" ".join(flags[i])} | {esc(r["EN"])} | {esc(r["AR"])} |')
    write(os.path.join(ROOT, 'review', 'FLAGS.md'), F)
    print(f'make_review: {len(where)} rows, {len(os.listdir(md))} pages')
