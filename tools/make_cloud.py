r"""Regenerate cloud_repo\ (git repo of the PRIVATE github.com/exelight7/KH3RM_AR_work) from the private project: exactly what a Linux
cloud review session needs (translation with EN+AR, review pages and script, corrections, Python tools, docs, state numbers).
Never copies game files, the AES key, extracted\, out\, fonts, screenshots, review\gpt\, public_repo\. Run tools\cloud_secret_check.py
and tools\cloud_check.py (inside cloud_repo\) after. Also rewrites review\cloud\TASKS.md here (row counts per range).
Usage: python -I tools\make_cloud.py"""
import os, re, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cloud_secret_check

ROOT = cloud_secret_check.ROOT
DST = os.path.join(ROOT, 'cloud_repo')
KEEP = {'.git'}
PY = ['validate', 'apply_corrections', 'make_script', 'make_review', 'stats', 'shaper', 'tsvlib', 'merge_translation', 'make_glossary',
      'locres', 'text_counts', 'cloud_check', 'cloud_secret_check', 'test_validate', 'test_corrections', 'test_shaper', 'test_cloud_secret_check']
FILES = ['CLOUD_RULES.md', 'PROJECT_MAP.md', '.gitattributes', '.github/workflows/check.yml', 'technical/theater_order.tsv',
         'state/STATS.md', 'state/PROGRESS.md', 'state/INSTALLED.tsv', 'state/SCREENSHOT_LOG.tsv', 'state/CLOUD_PROGRESS.md']
TREES = ['translation', 'review', 'docs']
SKIP = ('review/gpt/',)
RANGES = [(1, 8), (9, 16), (17, 24), (25, 32)]
TASKS = os.path.join(ROOT, 'review', 'cloud', 'TASKS.md')
CLOUD_GITIGNORE = '__pycache__/\n*.pyc\n'


def script_rows(page):
    s = open(os.path.join(ROOT, 'review', 'script', f'script_{page:03d}.md'), encoding='utf-8').read()
    return len(re.findall(r'^\| \d{5} \|', s, re.M))


def tasks_md():
    L = ['# Cloud review tasks (second pass)', '',
         'Generated by `tools/make_cloud.py`. One cloud session = one range. Read `CLOUD_RULES.md` first. Pages: `review/script/script_NNN.md`.',
         '',
         '| range | pages | rows | branch | status |', '|---|---|---|---|---|']
    for i, (a, b) in enumerate(RANGES, 1):
        n = sum(script_rows(p) for p in range(a, b + 1))
        L.append(f'| {i} | {a}-{b} (script_{a:03d}.md - script_{b:03d}.md) | {n} | `cloud/range-{i}` | open |')
    total = sum(script_rows(p) for p in range(1, 33))
    L += ['', f'Total: {total} rows (dialogue + cutscene subtitles in story order; menus, tips, journal and items are NOT in this task).', '',
          '## Review focus (second, deeper pass of the REVIEW-2 rows)', '',
          '1. Meaning against the EN line (missing or added content, wrong sense, wrong referent).',
          '2. Natural spoken Arabic per character: Sora simple and energetic, Donald quick-tempered, Goofy gentle with his fixed expressions, villains formal.',
          '3. Gender and number agreement for every pronoun and verb (check who speaks and who is addressed from the scene).',
          '4. Names and terms consistent across scenes (glossary first: `translation/glossary.tsv`).',
          '5. Subtitle length: validator RATIO warnings; keep near the EN length, same `<br>` count.',
          '6. Idioms and puns: flag them in `review/UNSURE_CLOUD.md`, do not invent a new joke.',
          '7. Repeated lines (same EN) translated identically.',
          '8. GLOSS warnings: fix those that are real errors, ignore false positives (note them in the commit message).',
          '', 'Rules, file formats and the pull request procedure: `CLOUD_RULES.md`.', '']
    return '\n'.join(L)


def clean(text, keys):
    return '\n'.join(l for l in text.split('\n') if not any(k in l for k in keys))


def put(rel, src, keys):
    d = os.path.join(DST, *rel.split('/'))
    os.makedirs(os.path.dirname(d), exist_ok=True)
    if rel.endswith(('.md', '.txt')):
        t = open(src, encoding='utf-8').read()
        open(d, 'w', encoding='utf-8', newline='\n').write(clean(t, keys) if keys else t)
    else:
        shutil.copyfile(src, d)


def main():
    keys = cloud_secret_check.key_values()
    os.makedirs(os.path.dirname(TASKS), exist_ok=True)
    open(TASKS, 'w', encoding='utf-8', newline='\n').write(tasks_md())
    os.makedirs(DST, exist_ok=True)
    for f in os.listdir(DST):
        if f in KEEP:
            continue
        p = os.path.join(DST, f)
        shutil.rmtree(p) if os.path.isdir(p) else os.remove(p)
    n = 0
    rels = list(FILES) + [f'tools/{m}.py' for m in PY]
    for t in TREES:
        for d, ds, fs in os.walk(os.path.join(ROOT, t)):
            ds.sort()
            for f in sorted(fs):
                rel = os.path.relpath(os.path.join(d, f), ROOT).replace(os.sep, '/')
                if not rel.startswith(SKIP) and '__pycache__' not in rel:
                    rels.append(rel)
    for rel in rels:
        src = os.path.join(ROOT, *rel.split('/'))
        if not os.path.exists(src):
            if rel == 'state/CLOUD_PROGRESS.md':
                continue
            raise SystemExit(f'make_cloud: missing {rel}')
        put(rel, src, keys)
        n += 1
    open(os.path.join(DST, '.gitignore'), 'w', newline='\n').write(CLOUD_GITIGNORE)
    bad = cloud_secret_check.run(DST)
    if bad:
        raise SystemExit('make_cloud: cloud_secret_check FAIL\n' + '\n'.join(bad))
    print(f'make_cloud: {n + 1} files written to {DST}')


if __name__ == '__main__':
    main()
